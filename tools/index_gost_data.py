    print("=" * 70)
    print("GOST/SP Standards Indexer for KMD Knowledge Base")
    print(f"Standards to index: {len(STANDARDS)}")
    print("=" * 70)

    # Show current stats
    try:
        stats = get_index_stats()
        ns = stats.get("namespaces", {})
        gost_ns = ns.get("gost-standards", {})
        print(f"\nCurrent gost-standards namespace: {gost_ns.get('record_count', 0)} records")
    except Exception as e:
        print(f"Warning: could not fetch stats: {e}")

    total_upserted = 0
    total_errors = []

    for i, std in enumerate(STANDARDS, 1):
        sid = std["id"]
        title = std["title"]
        text = std["text"]
        print(f"\n[{i}/{len(STANDARDS)}] Indexing {sid} — {title[:60]}...")

        try:
            result = index_gost_standard(
                text=text,
                standard_id=sid,
                title=title,
            )
            upserted = result.get("upserted", 0)
            errors = result.get("errors", [])
            total_upserted += upserted
            total_errors.extend(errors)
            print(f"  -> Upserted {upserted} chunks. Errors: {len(errors)}")
            if errors:
                for e in errors:
                    print(f"     ERROR: {e}")
        except Exception as e:
            print(f"  -> FAILED: {e}")
            total_errors.append(f"{sid}: {e}")

        # Brief pause between standards
        if i < len(STANDARDS):
            time.sleep(0.5)

