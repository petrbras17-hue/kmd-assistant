def index_all_hardware() -> dict:
    """Index all hardware/fittings data into Pinecone."""
    total = {"upserted": 0, "errors": []}
    for entry in HARDWARE_DATA:
        result = index_hardware(
            text=entry["text"],
            manufacturer=entry["manufacturer"],
            title=entry["title"],
        )
        total["upserted"] += result["upserted"]
        total["errors"].extend(result["errors"])
        print(f"  [HW] {entry['title']}: +{result['upserted']} records")
    return total


